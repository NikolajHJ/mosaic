"""Rebuild the packaged per-size ring frequencies from the uniform 60M-view training sample."""

import argparse
import csv
import gzip
import hashlib
from pathlib import Path

from rdkit import Chem, rdBase


PANEL_SHA256 = "2aff1053e38296cf319a13c72f5de958742c007502a16b4a8c7fe7521e6893b4"
VIEW_SHA256 = "64247d04ec1f94d00320bb1e5a0d9c5540419eb37830050d3100775bf4385e18"


def measure(panel):
    if hashlib.sha256(panel.read_bytes()).hexdigest() != PANEL_SHA256 or rdBase.rdkitVersion != "2024.09.6":
        raise ValueError("Reproduction requires the verified uniform training sample and RDKit 2024.09.6")
    counts = [[0, 0, 0] for _ in range(51)]
    ids = set()
    with gzip.open(panel, "rt", encoding="utf-8") as stream:
        for row in csv.DictReader(stream, delimiter="\t"):
            mol = Chem.MolFromSmiles(row["smiles"])
            hac = int(row["heavy_atoms"])
            if (mol is None or mol.GetNumHeavyAtoms() != hac or len(Chem.GetMolFrags(mol)) != 1
                    or not 1 <= hac <= 50 or row["view_row"] in ids):
                raise ValueError(f"Incompatible molecule or duplicate training row {row['view_row']}")
            ids.add(row["view_row"])
            sizes = [len(ring) for ring in mol.GetRingInfo().AtomRings()]
            counts[hac][0] += 1
            counts[hac][1] += 3 in sizes
            counts[hac][2] += any(size >= 8 for size in sizes)
    if len(ids) != 50_000:
        raise ValueError("Expected 50,000 distinct training rows")
    return counts


def render(counts):
    header = '''"""Size-matched rates of molecules containing a triangle or an eight-or-larger ring.

Generated by experiments/vae/training_data_eda/make_ring_size_reference.py from
50,000 uniform train rows sampled without replacement (seed 20261120). Each
row counts once per feature using RDKit 2024.09.6 AtomRings. Acyclic rows are
included in the denominator. Missing sizes have zero denominator.
"""

'''
    metadata = (f'REFERENCE_ID = "pubchem60m-train50k-v1"\nTRAINING_VIEW_SHA256 = "{VIEW_SHA256}"\n'
                f'PANEL_SHA256 = "{PANEL_SHA256}"\n')
    table = "\n".join(f"    ({n}, {triangle}, {large}),  # {size}"
                      for size, (n, triangle, large) in enumerate(counts))
    return header + metadata + "\n# Indexed by heavy-atom count: (sampled molecules, any triangle, any >=8 ring).\nCOUNTS_BY_HAC = (\n" + table + "\n)\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--panel", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    encoded = render(measure(args.panel)).encode("utf-8")
    if args.output.exists():
        if args.output.read_text(encoding="utf-8").encode("utf-8") != encoded:
            raise ValueError("Existing reference differs from the regenerated version")
    else:
        with args.output.open("xb") as stream:
            stream.write(encoded)
    print(hashlib.sha256(encoded).hexdigest(), args.output)


if __name__ == "__main__":
    main()
