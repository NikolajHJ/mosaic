"""Concrete VAE/native-scorer adapters for the alternating sampler callbacks.

The model and sampler modules remain frozen; all new contexts are generated by
the ordinary official Boltz parser for the graph and supplied pose. Admissions
carry paths to freshly executed certificates. The factory never manufactures a
global qualification pass, schedules a job or changes another experiment.
"""

from __future__ import annotations

from dataclasses import asdict
import importlib.util
import json
from pathlib import Path
import sys

import torch

from latentmol.data import sha256_file
from latentmol.boltz.contracts import AFFINITY_SHA256
from .alternation import (Admission, LatentProposal, LoopCallbacks, ObjectiveEvaluation,
                          bounded_latent_descent)
from .bridge import PILOT_ELEMENTS, exact_native_probabilities, hard_element_agreement
from .codec import FrozenVAECodec, encode_graph
from .native import FinalSample, authenticate_native_source
from .paired_data import check_deadline, write_json
from .pocket import audit_pose, validate_definition
from .scorer import (COMPONENTS, fixed_context_scores, load_scorer, qualify_context,
                     score_hard_native)
from .scorer_context import prepare_supplied_pose
from .transport import HandoffRejected, MolecularGraph, NativeBuilder, PoseCandidate


class GuidanceFactory:
    """One-process model owner and concrete callback set, with lazy Boltz load.

    ``native_info`` contains core, dataset_info, source (native load receipt's
    authenticated source object) and pocket (original native tensor dictionary).
    ``preparation_kwargs`` supplies receptor_pdb, msa_path, molecule_dir and both
    expected asset SHA256 values. ``assets`` contains affinity/confidence path/SHA
    dictionaries. Global sampler/transport qualification is the runner's job;
    ``qualification_evidence`` reports only certificates this factory executed.
    """

    def __init__(self, vae, boundary, bridge, native_info, pocket_definition,
                 preparation_kwargs, assets, output, device="cuda", deadline=None,
                 *, mode="learned", transport_stage="T1"):
        if mode not in ("learned", "exact") or transport_stage not in ("T1", "T2"):
            raise ValueError("Unknown mapping mode or transport stage")
        if mode == "learned" and bridge is None:
            raise ValueError("Learned alternation requires the authenticated trained head")
        self.vae, self.boundary, self.bridge = vae, boundary, bridge
        self.native_info, self.pocket_definition = native_info, validate_definition(pocket_definition)
        self.core, self.device = native_info["core"], torch.device(device)
        self.mode, self.transport_stage, self.deadline = mode, transport_stage, deadline
        self.preparation_kwargs, self.assets = dict(preparation_kwargs), assets
        self.output = Path(output)
        self.output.mkdir(parents=True, exist_ok=False)
        self.codec = FrozenVAECodec(vae, atom_count=25, device=self.device)
        self.decoder = tuple(native_info["dataset_info"]["atom_decoder"])
        self.native_atom_decoder = self.decoder
        if self.decoder != tuple(boundary.native_elements):
            raise ValueError("Mapping boundary vocabulary differs from authenticated native DiffSBDD")
        for module in (vae, boundary, self.core, *(() if bridge is None else (bridge,))):
            if module.training or any(p.requires_grad or p.grad is not None for p in module.parameters()):
                raise ValueError("Guidance models must be frozen eval modules with no stored gradients")
        if assets["affinity"]["sha256"] != AFFINITY_SHA256 or sha256_file(assets["affinity"]["path"]) != AFFINITY_SHA256:
            raise ValueError("Supplied-pose scorer affinity asset is not the pinned official checkpoint")
        source = native_info["source"]
        authenticated = authenticate_native_source(source["source_root"], source["manifest_sha256"])
        path = Path(authenticated["source_root"]) / "analysis" / "molecule_builder.py"
        if sha256_file(path) != authenticated["members"]["analysis/molecule_builder.py"]:
            raise ValueError("Native molecule builder changed after source authentication")
        spec = importlib.util.spec_from_file_location("_dbmol_pinned_diffsbdd_builder", path)
        module = importlib.util.module_from_spec(spec)
        sys.path.insert(0, authenticated["source_root"])
        try:
            spec.loader.exec_module(module)
        finally:
            sys.path.remove(authenticated["source_root"])
        self.native_builder = NativeBuilder(module.build_molecule, native_info["dataset_info"])
        self.scorer, self._counter = None, 0
        self._certificates = []
        self.callbacks = LoopCallbacks(self.admit_from_clean, self.propose,
            self.native_builder, self.rebuilt_objective, admit_control=self.admit_control)
        write_json(self.output / "factory.json", dict(version="diffsbdd-guidance-factory-v1",
            mode=mode, transport_stage=transport_stage, status="constructed_not_qualified",
            no_model_weights_trained=True, native_source_manifest_sha256=authenticated["manifest_sha256"],
            required_global_gates="native replay, exact boundary, trained mapping population/denoiser audit and T1/T2 transport",
            start_qualification_cost="recorded separately from latent-update gradient budget"))

    @property
    def qualification_evidence(self):
        """Only actual local certificate paths; no inferred global gate flags."""
        return dict(status="fresh_local_starts_qualified" if self._certificates else "no_start_qualified",
                    qualified_starts=len(self._certificates), certificates=list(self._certificates))

    def _next_path(self, kind):
        check_deadline(self.deadline)
        self._counter += 1
        return self.output / f"{self._counter:06d}-{kind}"

    def _slot_positions(self, candidate, slots):
        xyz = candidate.positions.new_zeros((self.vae.spec.max_nodes, 3))
        for native_index, slot in enumerate(slots.native_to_slot):
            xyz[slot] = candidate.positions[native_index]
        return xyz

    def _prepare(self, hard, slots, candidate, path):
        kwargs = dict(self.preparation_kwargs)
        kwargs["pocket_author_residues"] = [dict(chain=self.pocket_definition["protein_chain"],
            residue_number=row["author_residue"], insertion_code=row["insertion_code"])
            for row in self.pocket_definition["residues"]]
        return prepare_supplied_pose(hard, self.vae.spec, self._slot_positions(candidate, slots),
            output=path, persist_context=False, **kwargs).to(self.device)

    def _scorer_for(self, context):
        if self.scorer is None:
            self.scorer = load_scorer(self.assets["affinity"]["path"], self.assets["confidence"],
                                      context.pocket_residues, self.device)
        elif tuple(self.scorer.dbmol_config.pocket_residues) != tuple(context.pocket_residues):
            raise RuntimeError("A rebuilt context changed the frozen biological pocket identity")
        return self.scorer

    @torch.no_grad()
    def _mapping(self, latent, admitted):
        decoded, features = self.vae.decode_with_features(latent)
        active = admitted.active[None]
        exact = exact_native_probabilities(decoded, self.vae.spec, active, self.decoder,
                                          allowed_elements=PILOT_ELEMENTS)
        if self.mode == "learned":
            logits = self.bridge(features.atom_hidden)
            if not bool(hard_element_agreement(decoded, logits, self.vae.spec, active, self.bridge.elements).all()):
                raise HandoffRejected("ordinary_learned_hard_element_identity")
            probabilities = self.bridge.native_probabilities(features.atom_hidden, self.boundary, active)
        else:
            probabilities = exact.probabilities
        order = torch.tensor(admitted.slots.native_to_slot, device=latent.device, dtype=torch.long)
        mapped = probabilities[0].index_select(0, order).detach()
        symbols = tuple(self.decoder[index] for index in mapped.argmax(-1).cpu().tolist())
        receipt = dict(mode=self.mode, exact_control="explicit_six_conditioned",
            native_atom_order=admitted.slots.record(),
            mean_excluded_ordinary_probability_mass=float(exact.excluded_mass[active].mean()),
            maximum_excluded_ordinary_probability_mass=float(exact.excluded_mass[active].max()),
            mean_soft_non_neutral_charge_mass=float((1 - decoded.charges.softmax(-1)[
                ..., self.vae.spec.formal_charges.index(0)])[active].mean()),
            charge_transport="none; hard proposed graph must remain neutral",
            bond_transport="hard bonds require explicit graph/pose lifting and native reconstruction",
            occupancy_transport="fixed admitted 25 atoms; no atom birth or death",
            hard_mapping_elements=list(symbols))
        return mapped, symbols, receipt

    def _graph_from_cloud(self, positions, features):
        if positions.shape != (25, 3) or features.shape != (25, len(self.decoder)):
            raise HandoffRejected("native_clean_count_or_feature_width")
        symbols = tuple(self.decoder[index] for index in features.argmax(-1).cpu().tolist())
        placeholder = MolecularGraph(symbols, (0,) * 25,
            tuple((0,) * 25 for _ in range(25)), tuple(range(25)))
        graph, builder_receipt = self.native_builder(PoseCandidate(placeholder, positions))
        graph.require_pilot(25)
        return PoseCandidate(graph, positions.detach().clone()), builder_receipt

    def _admit_candidate(self, candidate, builder_receipt, frame_receipt, *, optimization=True):
        check_deadline(self.deadline)
        path = self._next_path("admission")
        path.mkdir()
        write_json(path / "input.json", dict(graph=asdict(candidate.graph),
            positions=candidate.positions.cpu().tolist(), native_builder=builder_receipt, frame=frame_receipt))
        pose = audit_pose(candidate.positions, self.pocket_definition)
        write_json(path / "pocket-pose.json", pose)
        if not pose["passed"]:
            raise HandoffRejected("candidate_not_in_frozen_biological_pocket", pose)
        modules = (self.vae, self.core, self.boundary, *(() if self.bridge is None else (self.bridge,)))
        versions = tuple((id(module), name, tensor._version) for module in modules
            for name, tensor in [*module.named_parameters(), *module.named_buffers()])
        recovered, rebuilt_receipt = self.native_builder(candidate)
        native_builder_identity = recovered == candidate.graph
        write_json(path / "native-builder-roundtrip.json", rebuilt_receipt)
        if not native_builder_identity:
            raise HandoffRejected("native_builder_complete_ordered_identity", rebuilt_receipt)
        admitted = self.codec.admit(candidate.graph)
        write_json(path / "codec.json", admitted.receipt)
        mapped, symbols, mapping_receipt = self._mapping(admitted.latent, admitted)
        if symbols != candidate.graph.elements:
            raise HandoffRejected("ordinary_mapping_hard_identity", mapping_receipt)
        write_json(path / "mapping.json", mapping_receipt)
        if not optimization:
            after = tuple((id(module), name, tensor._version) for module in modules
                for name, tensor in [*module.named_parameters(), *module.named_buffers()])
            frozen = versions == after and all(not module.training and not any(
                p.requires_grad or p.grad is not None for p in module.parameters()) for module in modules)
            checks = dict(native_builder_identity=native_builder_identity,
                ordinary_roundtrip_identity=admitted.receipt.get("complete_ordered_graph_identity") is True,
                adapter_hard_identity=symbols == candidate.graph.elements,
                pocket_frame=pose.get("passed") is True and frame_receipt.get("passed") is True,
                frozen_weights=frozen)
            receipt = dict(path=str(path.resolve()), mode=self.mode, codec=admitted.receipt,
                mapping=mapping_receipt, checks=checks, optimization=False,
                derivative_checks="not_run_for_noop", scorer_forward_calls=0, scorer_backward_calls=0,
                policy="H0 structural eligibility and exact no-op; global scorer qualification required by runner")
            write_json(path / "admission.json", receipt)
            result = Admission(admitted.latent, candidate, admitted.native_graph, mapped, checks,
                               dict(codec=admitted, path=path), receipt)
            result.require(25, optimization=False)
            return result
        context = self._prepare(admitted.natural_hard, admitted.slots, candidate, path / "context")
        scorer = self._scorer_for(context)
        qualification = qualify_context(scorer, context, self.vae, admitted.latent,
                                         path / "qualification", deadline=self.deadline)
        oracle = json.loads((path / "qualification" / "native-oracle.json").read_text())
        derivative = json.loads((path / "qualification" / "relaxed-start-ad.json").read_text())
        finite = json.loads((path / "qualification" / "resolved-fd.json").read_text())
        grouped = derivative.get("native_grouped_parity", {})
        checks = dict(
            native_pose_parity=oracle.get("existing_graph_vs_native", {}).get("passed") is True,
            component_derivatives=bool(grouped.get("reverse_exact")) and all(grouped["reverse_exact"].values()),
            total_derivative=grouped.get("production_total_reverse_exact") is True and finite.get("passed") is True,
            independent_primal_ad=bool(derivative.get("independent_forward_ad")) and all(
                row.get("passed") is True for row in derivative["independent_forward_ad"]),
            wrong_gradient_control=bool(finite.get("rows")) and all(row.get("wrong_gradient_control_rejected") is True
                                                                     for row in finite["rows"]),
            frozen_weights=qualification.get("frozen_context_and_models_unchanged") is True,
            pocket_frame=pose.get("passed") is True and frame_receipt.get("passed") is True,
            ordinary_roundtrip_identity=admitted.receipt.get("complete_ordered_graph_identity") is True,
            adapter_hard_identity=symbols == candidate.graph.elements)
        receipt = dict(path=str(path.resolve()), mode=self.mode, codec=admitted.receipt,
            mapping=mapping_receipt, checks=checks, qualification=qualification,
            qualification_gradient_calls_are_diagnostics=True,
            native_oracle_calls=oracle.get("calls"), independent_ad_calls=derivative.get("calls"))
        write_json(path / "admission.json", receipt)
        result = Admission(admitted.latent, candidate, admitted.native_graph, mapped, checks,
                           dict(codec=admitted, supplied=context, scorer=scorer, path=path), receipt)
        result.require(25)
        self._certificates.append(dict(admission=str((path / "admission.json").resolve()),
                                       qualification=str((path / "qualification" / "qualification.json").resolve())))
        return result

    def _admit_from_clean(self, state, clean, *, optimization):
        check_deadline(self.deadline)
        raw_pocket = self.native_info["pocket"]["x"].to(state.pocket)
        actual = (state.pocket[:, :3] + state.frame_offset[state.pocket_mask]) * float(self.core.norm_values[0])
        passed = actual.shape == raw_pocket.shape and torch.allclose(actual, raw_pocket, atol=2e-5, rtol=2e-5)
        if not passed:
            raise RuntimeError("Diffusion pocket frame/geometry differs from original authenticated receptor")
        candidate, builder = self._graph_from_cloud(clean.positions, clean.features)
        return self._admit_candidate(candidate, builder,
            dict(passed=bool(passed), policy="tracked native joint translation"), optimization=optimization)

    def admit_from_clean(self, state, clean):
        return self._admit_from_clean(state, clean, optimization=True)

    def admit_control(self, state, clean):
        return self._admit_from_clean(state, clean, optimization=False)

    def admit_terminal(self, terminal):
        if isinstance(terminal, FinalSample):
            raw_pocket = self.native_info["pocket"]["x"].to(terminal.pocket_positions)
            passed = terminal.pocket_positions.shape == raw_pocket.shape and torch.allclose(
                terminal.pocket_positions, raw_pocket, atol=2e-5, rtol=2e-5)
            if not passed:
                raise RuntimeError("Terminal native pocket geometry/frame changed")
            candidate, builder = self._graph_from_cloud(terminal.positions, terminal.one_hot)
        elif isinstance(terminal, PoseCandidate):
            candidate, builder = terminal, {"supplied_complete_graph": True}
            # A PoseCandidate has no pocket tensors; verify its original-frame
            # geometry against the authenticated pocket in _admit_candidate.
            passed = bool(audit_pose(candidate.positions, self.pocket_definition)["passed"])
        else:
            raise TypeError("Terminal admission requires a native final sample or explicit pose candidate")
        return self._admit_candidate(candidate, builder, dict(passed=bool(passed), policy="terminal receptor frame"))

    def propose(self, admission, max_updates):
        check_deadline(self.deadline)
        state = admission.context
        admitted, supplied, scorer = state["codec"], state["supplied"], state["scorer"]

        def objective(z):
            check_deadline(self.deadline)
            scores = fixed_context_scores(scorer, supplied.prepared, self.vae, z)
            graph = self.codec.relaxed(z, admitted)
            return ObjectiveEvaluation(scores["dbmol_total_loss"].reshape(()), graph.atoms, graph.bonds,
                {key: scores[key].reshape(()) for key in COMPONENTS if key != "dbmol_total_loss"})

        frozen = (self.vae, self.core, self.boundary, scorer, *(() if self.bridge is None else (self.bridge,)))

        @torch.no_grad()
        def describe_proposal(z):
            try:
                return self.codec.decode(z, admitted).receipt
            except HandoffRejected as error:
                decoded = self.vae.decode(z)
                natural = decoded.harden(self.vae.spec)
                soft = self.codec.relaxed(z, admitted)
                return dict(eligible=False, reason=str(error), receipt=error.receipt,
                    natural=dict(atoms=natural.atoms.cpu().tolist(), charges=natural.charges.cpu().tolist(),
                                 bonds=natural.bonds.cpu().tolist()),
                    conditioned=dict(atoms=soft.atoms.argmax(-1).cpu().tolist(),
                        charges=soft.charges.argmax(-1).cpu().tolist(), bonds=soft.bonds.argmax(-1).cpu().tolist()))

        result = bounded_latent_descent(admission.latent, objective, max_updates,
            frozen_modules=frozen, describe_proposal=describe_proposal)
        decoded = self.codec.decode(result.latent, admitted)
        mapped, symbols, mapping = self._mapping(result.latent, admitted)
        path = self._next_path("proposal")
        path.mkdir()
        receipt = dict(descent=result.receipt, decode=decoded.receipt, mapping=mapping,
            fixed_context_path=str(state["path"]), path=str(path.resolve()),
            hard_graph=asdict(decoded.graph), transport_stage=self.transport_stage)
        write_json(path / "proposal.json", receipt)
        return LatentProposal(result.latent, decoded.graph, mapped, symbols, receipt)

    def rebuilt_objective(self, candidate):
        check_deadline(self.deadline)
        candidate.graph.require_pilot(25)
        encoded = encode_graph(candidate.graph, self.vae.spec, self.device)
        path = self._next_path("rebuilt-hard")
        context = self._prepare(encoded.hard, encoded.slots, candidate, path)
        scores = score_hard_native(self._scorer_for(context), context)
        scores["total"] = scores["dbmol_total_loss"]
        write_json(path / "hard-native-scores.json", scores)
        return scores


def build_guidance(vae, bridge, boundary, core, pocket_artifact, scorer_assets,
                   preparation_assets, output, *, mode="learned", transport_stage="T1",
                   device="cuda", deadline=None):
    """Convenience constructor returning the factory (use ``.callbacks``)."""
    native_info = dict(core=core, dataset_info=pocket_artifact["dataset_info"],
        source=pocket_artifact["source"], pocket=pocket_artifact["pocket"])
    return GuidanceFactory(vae, boundary, bridge, native_info, pocket_artifact["definition"],
        preparation_assets, scorer_assets, output, device, deadline,
        mode=mode, transport_stage=transport_stage)
